/* Adds one <url> per indexable product page to sitemap.xml.
   "Indexable" means: it has a page (a photo and a price), and it is the page
   that owns its name. Products still carrying a generated placeholder name are
   left out until they are named, and the noindex pages stay out. */
const fs = require("fs");
const path = require("path");

const ROOT = "/home/abdullah/Desktop/Gulnish Crochet";
const { loadCatalog, priceText } = require(path.join(ROOT, "scripts", "generate-product-pages.js"));

const ORIGIN = "https://gulnishcrochet.vercel.app";
const DATE = process.env.SITEMAP_DATE || new Date().toISOString().slice(0, 10);

const GENERATED_NAME = /^(purses?|bags?|gajrays?|bouquets?|jewellery|headbands?|keychains?|geometry|pencil)\s+\d+$/i;

/* Walk the static <url> entries and:
   - drop any page whose HTML carries a noindex meta (e.g. a shelf with no
     products yet), so the sitemap never advertises a page that asks crawlers
     to stay away;
   - rewrite each <lastmod> from the file's real modification time, so the
     dates the sitemap publishes are true instead of whatever was typed by
     hand when the entry was first added. */
function refreshStaticEntries(xml) {
  return xml.replace(/ {2}<url>[\s\S]*?<\/url>\n/g, (block) => {
    const loc = block.match(/<loc>([^<]+)<\/loc>/);
    if (!loc) return block;
    const pathname = decodeURIComponent(loc[1].replace(/^https?:\/\/[^/]+/, ""));
    const rel = pathname.replace(/^\//, "").replace(/\/$/, "");
    const candidates = [
      path.join(ROOT, rel + ".html"),
      path.join(ROOT, rel, "index.html"),
    ];
    let file = null;
    for (const c of candidates) {
      if (fs.existsSync(c)) { file = c; break; }
    }
    if (!file) return block;
    const html = fs.readFileSync(file, "utf8");
    if (/<meta\s+name="robots"[^>]*noindex/i.test(html)) return "";
    const date = fs.statSync(file).mtime.toISOString().slice(0, 10);
    return block.replace(/<lastmod>[^<]*<\/lastmod>/, `<lastmod>${date}</lastmod>`);
  });
}

/* init() resolves when the catalogue is populated, not with the catalogue
   itself, so the GC object has to be held on to separately. */
const GC = loadCatalog();

GC.init()
  .then(() => {
    const products = GC.products || [];
    const slugs = new Map();
    for (const p of products) {
      if (!p.image || !(parseFloat(p.price) > 0)) continue;
      const name = String(p.name || "").trim();
      if (!name || GENERATED_NAME.test(name)) continue; /* placeholder name */
      slugs.set(GC.canonicalProductSlug(p), { name, price: priceText(p) });
    }

    const file = path.join(ROOT, "sitemap.xml");
    let xml = fs.readFileSync(file, "utf8");

    /* Drop any product block a previous run wrote, then append a fresh one.
       Keeping this idempotent matters: the file is committed, so a second run
       must not double the list. */
    xml = xml.replace(/  <!-- PRODUCT PAGES START -->[\s\S]*?<!-- PRODUCT PAGES END -->\n/g, "");

    const entries = [...slugs.entries()]
      .sort((a, b) => a[0].localeCompare(b[0]))
      .map(
        ([slug]) =>
          `  <url>\n` +
          `    <loc>${ORIGIN}/product/${slug}</loc>\n` +
          `    <lastmod>${DATE}</lastmod>\n` +
          `    <changefreq>weekly</changefreq>\n` +
          `    <priority>0.7</priority>\n` +
          `  </url>\n`
      )
      .join("");

    const block =
      `  <!-- PRODUCT PAGES START -->\n` +
      `  <!-- One URL per product page. Generated by scripts/sitemap-products.js\n` +
      `       from the same catalogue the pages themselves are generated from, so\n` +
      `       the list and the pages cannot drift apart. Products still carrying a\n` +
      `       placeholder name are not listed until they are given a real one. -->\n` +
      entries +
      `  <!-- PRODUCT PAGES END -->\n`;

    xml = xml.replace("</urlset>", block + "</urlset>");
    fs.writeFileSync(file, xml);
    console.log(`[sitemap] ${slugs.size} product URL(s) written (total now ${(xml.match(/<loc>/g) || []).length})`);
  })
  .catch((err) => {
    console.error("[sitemap]", err.message.trim());
    process.exitCode = 1;
  });